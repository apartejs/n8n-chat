/**
 * The CDN build: one module a page imports from a script tag, aparté inside it, so a page
 * with no build step loads one file and its stylesheet — the way n8n's own widget is embedded.
 * What only some pages need stays in chunks beside it, fetched when used: a language other
 * than English, the highlighter with the first code block.
 *
 * esbuild rather than Vite's library mode: measured on the same entry, Vite's output was
 * 163 KB brotli for the first load and esbuild's 99 KB.
 */
import { build } from 'esbuild';
import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outdir = resolve(pkg, 'dist/cdn');
rmSync(outdir, { recursive: true, force: true });
await build({
    entryPoints: { 'n8n-chat': resolve(pkg, 'src/index.ts') },
    outdir,
    bundle: true,
    splitting: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    sourcemap: true,
    chunkNames: 'chunks/[name]-[hash]',
    logLevel: 'warning',
});
console.log('[n8n-chat] dist/cdn/n8n-chat.js, aparté inside');

// latest.js: what a page loads through a version range (`@aparte/n8n-chat@1/dist/cdn/latest.js`) to get each 1.x
// on its own. A range is not redirected: jsDelivr serves its files under `@1/` and a browser keeps them a week, so
// n8n-chat.js loaded that way could be last week's while its chunks, named by content hash and fetched under the
// same `@1/`, come from this week's version and are not there. This file names ONE exact version, for the module
// and for its stylesheet: a cached copy still points at a whole version, and the next one arrives as a whole.
// The stylesheet is waited for, so the chat never draws unstyled.
const { version } = JSON.parse(readFileSync(resolve(pkg, 'package.json'), 'utf8'));
const base = `https://cdn.jsdelivr.net/npm/@aparte/n8n-chat@${version}/dist`;
writeFileSync(resolve(outdir, 'latest.js'), `// @aparte/n8n-chat ${version}: the module and its stylesheet, from one exact version. Generated by scripts/build-cdn.mjs.
if (!document.querySelector('link[data-aparte-n8n-chat]')) {
    const link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = '${base}/style.css';
    link.dataset.aparteN8nChat = '${version}';
    const loaded = new Promise((done) => { link.onload = link.onerror = done; });
    document.head.append(link);
    await loaded;
}
export * from '${base}/cdn/n8n-chat.js';
`);
console.log(`[n8n-chat] dist/cdn/latest.js → ${version}`);
